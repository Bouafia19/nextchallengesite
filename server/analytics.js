import crypto from 'node:crypto'
import VisitorAnalytics from './models/VisitorAnalytics.js'
import DailyVisitor from './models/DailyVisitor.js'
import DailySession from './models/DailySession.js'

export const ANALYTICS_ACTIVATION_DATE = '2026-10-29'

// Known bot / crawler signatures
const BOT_REGEX = /(bot|crawler|spider|slurp|crawling|googlebot|bingbot|yandex|baidu|duckduckbot|facebookexternalhit|linkedinbot|whatsapp|twitterbot|slackbot|pinterest|semrush|ahrefs|mj12bot|dotbot|curl|wget|python|urllib|httpie|postman|headlesschrome|puppeteer|playwright|selenium|lighthouse|pagespeed|gtmetrix|uptime|pingdom|render|healthcheck|monitor)/i

/**
 * Checks whether the incoming request is generated by a bot or automated crawler.
 */
export function isBotRequest(userAgent) {
  if (!userAgent || typeof userAgent !== 'string' || !userAgent.trim()) {
    return true
  }
  return BOT_REGEX.test(userAgent)
}

/**
 * Generates an anonymous, irreversible HMAC hash using the server secret salt.
 * Ensures visitor IDs are never stored in raw form.
 */
function hashToken(token) {
  const salt = process.env.ANALYTICS_SALT || process.env.ADMIN_API_KEY || 'nc_analytics_salt_prod_2026'
  return crypto.createHmac('sha256', salt).update(String(token || '').trim()).digest('hex')
}

/**
 * Parses device category from string or fallback user-agent
 */
function parseDevice(device, userAgent = '') {
  if (device === 'mobile' || device === 'tablet' || device === 'desktop') {
    return device
  }
  const ua = String(userAgent).toLowerCase()
  if (/(tablet|ipad|playbook|silk)|(android(?!.*mobi))/i.test(ua)) return 'tablet'
  if (/Mobile|iP(hone|od)|Android|BlackBerry|IEMobile|Kindle|NetFront|Silk-Accelerated|(hpw|web)OS|Fennec|Minimo|Opera M(obi|ini)|Blazer/i.test(ua)) return 'mobile'
  return 'desktop'
}

/**
 * Parses browser family from string or fallback user-agent
 */
function parseBrowser(browser, userAgent = '') {
  const clean = String(browser || '').toLowerCase()
  if (['chrome', 'safari', 'firefox', 'edge'].includes(clean)) {
    return clean
  }
  const ua = String(userAgent).toLowerCase()
  if (ua.includes('edg/') || ua.includes('edge/')) return 'edge'
  if (ua.includes('firefox/') || ua.includes('fxios/')) return 'firefox'
  if (ua.includes('chrome/') || ua.includes('crios/')) return 'chrome'
  if (ua.includes('safari/') && !ua.includes('chrome/')) return 'safari'
  return 'other'
}

/**
 * Sanitizes page path to standard clean format
 */
function sanitizePath(rawPath) {
  if (!rawPath || typeof rawPath !== 'string') return '/'
  let clean = rawPath.trim().split('?')[0].split('#')[0]
  if (!clean.startsWith('/')) clean = `/${clean}`
  // Normalize repeated slashes
  clean = clean.replace(/\/+/g, '/')
  return clean.slice(0, 100) || '/'
}

/**
 * Helper to generate UTC date string 'YYYY-MM-DD'
 */
export function getUtcDateString(date = new Date()) {
  return date.toISOString().slice(0, 10)
}

/**
 * Helper to compute an offset UTC date string
 */
export function getOffsetDateString(daysOffset = 0) {
  const d = new Date()
  d.setUTCDate(d.getUTCDate() + daysOffset)
  return d.toISOString().slice(0, 10)
}

/**
 * Records a visitor hit asynchronously.
 * Guarantees zero duplicate counting for unique visitors and sessions.
 */
export async function recordVisit({
  visitorId,
  sessionId,
  path = '/',
  device = 'desktop',
  browser = 'chrome',
  userAgent = '',
  isClientNew = false
}) {
  if (isBotRequest(userAgent)) {
    return { recorded: false, reason: 'bot_excluded' }
  }

  const cleanPath = sanitizePath(path)

  // Disallow tracking administrative or sensitive routes
  const adminRoute = (process.env.ADMIN_ROUTE_PATH || '/administrator-').toLowerCase()
  if (
    cleanPath.toLowerCase().startsWith('/admin') ||
    cleanPath.toLowerCase().startsWith(adminRoute) ||
    cleanPath.includes('health') ||
    cleanPath.includes('security')
  ) {
    return { recorded: false, reason: 'admin_or_system_route_excluded' }
  }

  const today = getUtcDateString()
  const visitorHash = hashToken(visitorId)
  const sessionHash = hashToken(sessionId)
  const deviceType = parseDevice(device, userAgent)
  const browserType = parseBrowser(browser, userAgent)

  let isUniqueVisitorToday = false
  let isReturningVisitor = false

  // 1. Deduplicate Unique Visitor per Day via DailyVisitor collection
  try {
    await DailyVisitor.create({
      date: today,
      visitorHash
    })
    isUniqueVisitorToday = true

    // Check if this visitor has visited on any prior date
    const prior = await DailyVisitor.findOne({
      visitorHash,
      date: { $ne: today }
    }).select('_id').lean()

    isReturningVisitor = Boolean(prior)
  } catch (err) {
    if (err.code === 11000) {
      // Already visited today
      isUniqueVisitorToday = false
    } else {
      console.warn('[Analytics] DailyVisitor insert error:', err.message || err)
    }
  }

  // 2. Deduplicate Session / Visit per Day via DailySession collection
  let isNewSessionToday = false
  try {
    await DailySession.create({
      date: today,
      sessionHash
    })
    isNewSessionToday = true
  } catch (err) {
    if (err.code === 11000) {
      isNewSessionToday = false
    } else {
      console.warn('[Analytics] DailySession insert error:', err.message || err)
    }
  }

  // 3. Prepare atomic $inc update for aggregated VisitorAnalytics
  const inc = {}

  if (isUniqueVisitorToday) {
    inc.uniqueVisitors = 1
    if (isReturningVisitor) {
      inc.returningVisitors = 1
    } else {
      inc.newVisitors = 1
    }
  }

  if (isNewSessionToday) {
    inc.totalVisits = 1
    if (deviceType) inc[`devices.${deviceType}`] = 1
    if (browserType) inc[`browsers.${browserType}`] = 1
  }

  // 4. Update Daily Aggregation and Top Pages atomically
  try {
    // Attempt updating topPages array if path already exists
    const incForPath = {
      ...inc,
      'topPages.$.views': 1
    }

    const updated = await VisitorAnalytics.findOneAndUpdate(
      { date: today, 'topPages.path': cleanPath },
      {
        $inc: incForPath,
        $set: { updatedAt: new Date() }
      },
      { returnDocument: 'after' }
    )

    if (!updated) {
      // Document or path does not exist in topPages yet; push new path entry
      const insertUpdate = {
        $push: {
          topPages: {
            $each: [{ path: cleanPath, views: 1 }],
            $slice: 50 // Keep top 50 paths to prevent unbounded growth
          }
        },
        $setOnInsert: { date: today },
        $set: { updatedAt: new Date() }
      }

      if (Object.keys(inc).length > 0) {
        insertUpdate.$inc = inc
      }

      await VisitorAnalytics.findOneAndUpdate(
        { date: today },
        insertUpdate,
        { upsert: true, returnDocument: 'after' }
      )
    }

    return {
      recorded: true,
      isUniqueVisitorToday,
      isNewSessionToday,
      isReturningVisitor
    }
  } catch (err) {
    console.error('[Analytics] Aggregation update error:', err.message || err)
    return { recorded: false, error: err.message || err }
  }
}

/**
 * Retrieves aggregated visitor analytics for the admin dashboard.
 * Supports 7d, 30d, 90d periods.
 */
export async function getVisitorAnalytics(range = '30d') {
  let days = 30
  if (range === '7d' || range === '7') days = 7
  else if (range === '90d' || range === '90') days = 90
  else days = 30

  const today = getUtcDateString()
  const yesterday = getOffsetDateString(-1)
  const last7DaysStart = getOffsetDateString(-6) // inclusive 7 days
  const last30DaysStart = getOffsetDateString(-29) // inclusive 30 days
  const rangeStart = getOffsetDateString(-(days - 1))

  // Fetch all historical records within range and all-time totals
  const [rangeDocs, allDocs] = await Promise.all([
    VisitorAnalytics.find({ date: { $gte: rangeStart, $lte: today } })
      .sort({ date: 1 })
      .lean(),
    VisitorAnalytics.find({}).select('uniqueVisitors totalVisits newVisitors returningVisitors').lean()
  ])

  const docMap = new Map()
  for (const doc of rangeDocs) {
    docMap.set(doc.date, doc)
  }

  // Build continuous daily history for the entire requested date range
  const dailyHistory = []
  let sumRangeUnique = 0
  let sumRangeVisits = 0
  let sumRangeNew = 0
  let sumRangeReturning = 0

  const pageViewsMap = new Map()
  const devicesTotal = { desktop: 0, mobile: 0, tablet: 0 }
  const browsersTotal = { chrome: 0, safari: 0, firefox: 0, edge: 0, other: 0 }

  for (let i = days - 1; i >= 0; i--) {
    const curDate = getOffsetDateString(-i)
    const existing = docMap.get(curDate)
    const isPreActivation = curDate < ANALYTICS_ACTIVATION_DATE

    const dayData = {
      date: curDate,
      uniqueVisitors: existing?.uniqueVisitors || 0,
      totalVisits: existing?.totalVisits || 0,
      newVisitors: existing?.newVisitors || 0,
      returningVisitors: existing?.returningVisitors || 0,
      isPreActivation
    }

    dailyHistory.push(dayData)

    sumRangeUnique += dayData.uniqueVisitors
    sumRangeVisits += dayData.totalVisits
    sumRangeNew += dayData.newVisitors
    sumRangeReturning += dayData.returningVisitors

    if (existing) {
      if (Array.isArray(existing.topPages)) {
        for (const p of existing.topPages) {
          pageViewsMap.set(p.path, (pageViewsMap.get(p.path) || 0) + (p.views || 0))
        }
      }
      if (existing.devices) {
        devicesTotal.desktop += existing.devices.desktop || 0
        devicesTotal.mobile += existing.devices.mobile || 0
        devicesTotal.tablet += existing.devices.tablet || 0
      }
      if (existing.browsers) {
        browsersTotal.chrome += existing.browsers.chrome || 0
        browsersTotal.safari += existing.browsers.safari || 0
        browsersTotal.firefox += existing.browsers.firefox || 0
        browsersTotal.edge += existing.browsers.edge || 0
        browsersTotal.other += existing.browsers.other || 0
      }
    }
  }

  // Format Top Pages sorted descending
  const topPages = Array.from(pageViewsMap.entries())
    .map(([path, views]) => ({ path, views }))
    .sort((a, b) => b.views - a.views)
    .slice(0, 10)

  // Calculate All-time stats from all docs
  let allTimeUniqueVisitors = 0
  let allTimeTotalVisits = 0
  for (const doc of allDocs) {
    // Unique visitors all-time is the sum of newVisitors (each visitor's first day)
    allTimeUniqueVisitors += (doc.newVisitors || doc.uniqueVisitors || 0)
    allTimeTotalVisits += (doc.totalVisits || 0)
  }

  // Find today's and yesterday's metrics
  const todayDoc = docMap.get(today) || (await VisitorAnalytics.findOne({ date: today }).lean()) || {}
  const yesterdayDoc = docMap.get(yesterday) || (await VisitorAnalytics.findOne({ date: yesterday }).lean()) || {}

  // Last 7 days slice from dailyHistory (last 7 items)
  const last7DaysSlice = dailyHistory.slice(-7)
  const last7DaysVisitors = last7DaysSlice.reduce((acc, d) => acc + d.uniqueVisitors, 0)
  const last7DaysVisits = last7DaysSlice.reduce((acc, d) => acc + d.totalVisits, 0)

  // Last 30 days slice
  const last30DaysSlice = dailyHistory.slice(-30)
  const last30DaysVisitors = last30DaysSlice.reduce((acc, d) => acc + d.uniqueVisitors, 0)
  const last30DaysVisits = last30DaysSlice.reduce((acc, d) => acc + d.totalVisits, 0)

  return {
    success: true,
    activationDate: ANALYTICS_ACTIVATION_DATE,
    range: `${days}d`,
    summary: {
      totalVisitors: allTimeUniqueVisitors,
      totalVisits: allTimeTotalVisits,
      todayVisitors: todayDoc.uniqueVisitors || 0,
      todayVisits: todayDoc.totalVisits || 0,
      yesterdayVisitors: yesterdayDoc.uniqueVisitors || 0,
      yesterdayVisits: yesterdayDoc.totalVisits || 0,
      last7DaysVisitors,
      last7DaysVisits,
      last30DaysVisitors,
      last30DaysVisits,
      newVisitors: sumRangeNew,
      returningVisitors: sumRangeReturning
    },
    dailyHistory,
    topPages,
    devices: devicesTotal,
    browsers: browsersTotal
  }
}
